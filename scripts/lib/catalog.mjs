import fs from "node:fs";
import path from "node:path";

export function readJson(file) {
  let text = fs.readFileSync(file, "utf8");
  if (text.charCodeAt(0) === 0xfeff) text = text.slice(1);
  return JSON.parse(text);
}

export function loadRaw(root) {
  const ingredientDir = path.join(root, "data", "ingredients");
  const dayDir = path.join(root, "data", "days");
  const ingredients = [];
  for (const file of fs.readdirSync(ingredientDir).filter((name) => name.endsWith(".json")).sort()) {
    ingredients.push({
      file,
      data: readJson(path.join(ingredientDir, file))
    });
  }
  const days = [];
  for (const file of fs.readdirSync(dayDir).filter((name) => name.endsWith(".json")).sort()) {
    days.push({
      file,
      data: readJson(path.join(dayDir, file))
    });
  }
  return { ingredients, days };
}

function sortKeys(value) {
  if (Array.isArray(value)) return value.map(sortKeys);
  if (value && typeof value === "object") {
    const out = {};
    for (const key of Object.keys(value).sort()) out[key] = sortKeys(value[key]);
    return out;
  }
  return value;
}

export function buildCatalog(raw) {
  const byId = new Map();
  for (const entry of raw.ingredients) {
    const id = entry.data && entry.data.id;
    if (!id || byId.has(id)) {
      throw new Error("原料 id 重複或缺少：" + entry.file);
    }
    byId.set(id, entry.data);
  }
  const days = raw.days
    .map((entry) => {
      const picks = Array.isArray(entry.data.picks) ? entry.data.picks : [];
      const items = picks.map((id) => {
        const ingredient = byId.get(id);
        if (!ingredient) throw new Error(entry.file + " 引用了不存在的原料 " + id);
        return ingredient;
      });
      return {
        date: entry.data.date,
        example: entry.data.example === true,
        title: entry.data.title || "",
        targetCount: entry.data.targetCount || 5,
        channelsCovered: entry.data.channelsCovered || [],
        notes: entry.data.notes || "",
        picks: items
      };
    })
    .sort((a, b) => (a.date < b.date ? 1 : a.date > b.date ? -1 : 0));

  return sortKeys({
    version: 1,
    ingredients: raw.ingredients.map((entry) => entry.data),
    days
  });
}

export function serializeCatalog(catalog) {
  const json = JSON.stringify(catalog, null, 2).replace(/</g, "\\u003c");
  const js = "/* Generated by scripts/build-catalog.mjs. Do not edit. */\nwindow.INGREDIENT_CATALOG = " + json + ";\n";
  return {
    json: JSON.stringify(catalog, null, 2).replace(/</g, "\\u003c") + "\n",
    js
  };
}
